/* Builds habits/emoji-data.js: every standard emoji, for the picker (2.20).

   Sources (download them first; they are not kept in the repository):
     emoji-test.txt                  https://unicode.org/Public/emoji/latest/emoji-test.txt
     annotations-<lang>.json         cldr-json: cldr-annotations-full/annotations/<lang>/annotations.json
     annotationsDerived-<lang>.json  cldr-json: cldr-annotations-derived-full/annotationsDerived/<lang>/annotations.json
   for es and en, all in one folder:
     node tools/emoji/make-emoji-data.js <folder>

   What it keeps: each fully-qualified emoji (no components), in Unicode's
   order and groups, with the emoji version that brought it (the picker hides
   what the phone cannot draw), its name and a few keywords in Spanish and
   English (CLDR), and, where Unicode has them, its five skin tones (only the
   uniform ones; a couple with two tones is left out). Nothing is drawn as an
   image: the phone's own emoji font draws them. */
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
if (!dir) { console.error('usage: node make-emoji-data.js <folder with the sources>'); process.exit(1); }
const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'habits', 'emoji-data.js');
const KEYWORDS = 4;                         // per language, after the name

const GROUPS = {
  'Smileys & Emotion': 'smileys', 'People & Body': 'people', 'Animals & Nature': 'nature',
  'Food & Drink': 'food', 'Travel & Places': 'travel', 'Activities': 'activities',
  'Objects': 'objects', 'Symbols': 'symbols', 'Flags': 'flags',
};
const TONES = ['light skin tone', 'medium-light skin tone', 'medium skin tone', 'medium-dark skin tone', 'dark skin tone'];

function annotations(lang) {
  const read = (file) => {
    const json = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    const root = json.annotations || json.annotationsDerived;
    return root.annotations;
  };
  return Object.assign({}, read('annotations-' + lang + '.json'), read('annotationsDerived-' + lang + '.json'));
}
const NAMES = { es: annotations('es'), en: annotations('en') };
const strip = (s) => s.replace(/\uFE0F/g, '');
function words(lang, emoji, fallback) {
  const a = NAMES[lang][emoji] || NAMES[lang][strip(emoji)];
  const name = a && a.tts && a.tts[0] ? a.tts[0] : fallback;
  const keys = a && a.default ? a.default.filter((k) => k !== name).slice(0, KEYWORDS) : [];
  return { name: name, keys: keys };
}

// Unicode's list.
const lines = fs.readFileSync(path.join(dir, 'emoji-test.txt'), 'utf8').split(/\r?\n/);
let group = null;
const base = [];                            // { emoji, group, version, name }
const byName = new Map();
const tones = new Map();                    // base name -> [5 variants]
for (const line of lines) {
  const g = /^# group: (.+)$/.exec(line);
  if (g) { group = GROUPS[g[1]] || null; continue; }
  if (!group || line.startsWith('#') || !line.trim()) continue;
  const m = /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$/.exec(line);
  if (!m) continue;
  const [, emoji, version, name] = m;
  const colon = name.indexOf(': ');
  const head = colon < 0 ? name : name.slice(0, colon);
  const quals = colon < 0 ? [] : name.slice(colon + 2).split(', ');
  const toneQuals = quals.filter((q) => TONES.includes(q));
  if (toneQuals.length) {
    // A toned variant: only one tone named (uniform), filed under its untoned name.
    if (toneQuals.length !== 1 || quals.filter((q) => q === toneQuals[0]).length !== 1) continue;
    const rest = quals.filter((q) => !TONES.includes(q));
    const baseName = rest.length ? head + ': ' + rest.join(', ') : head;
    if (!tones.has(baseName)) tones.set(baseName, new Array(5).fill(null));
    tones.get(baseName)[TONES.indexOf(toneQuals[0])] = emoji;
    continue;
  }
  const entry = { emoji: emoji, group: group, version: version, name: name };
  base.push(entry);
  byName.set(name, entry);
}

const groups = Object.values(GROUPS);
const rows = base.map((e) => {
  const es = words('es', e.emoji, e.name);
  const en = words('en', e.emoji, e.name);
  const t = tones.get(e.name);
  const toned = t && t.every(Boolean) ? t.join(' ') : '';
  // emoji | group | version | es name | en name | es keywords | en keywords | 5 tones
  return [e.emoji, groups.indexOf(e.group), e.version, es.name, en.name, es.keys.join(','), en.keys.join(','), toned]
    .map((x) => String(x).replace(/[|\n]/g, ' ')).join('|');
});

const header = '/* Every standard emoji for the picker, generated by tools/emoji/make-emoji-data.js\n' +
  '   from Unicode emoji-test.txt and CLDR annotations (Unicode License v3). Do not edit:\n' +
  '   one emoji a line: emoji|group|version|es name|en name|es keywords|en keywords|five skin tones. */\n';
const body = 'window.GLOW_EMOJI_DATA = {\n  groups: ' + JSON.stringify(groups) + ',\n  rows: ' + JSON.stringify(rows.join('\n')) + ',\n};\n';
fs.writeFileSync(OUT, header + body);
const withTones = rows.filter((r) => r.split('|')[7]).length;
console.log(rows.length + ' emojis (' + withTones + ' with skin tones) in ' + groups.length + ' groups -> ' +
  path.relative(ROOT, OUT) + ', ' + Math.round(fs.statSync(OUT).size / 1024) + ' KB');
